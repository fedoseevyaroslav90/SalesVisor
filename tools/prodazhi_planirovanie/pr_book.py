def table(ws, r0, headers, data, widths=None, center_from=2):
    for j, h in enumerate(headers, 1):
        c = ws.cell(r0, j, h)
        c.font, c.fill, c.alignment = HDR, HF, Alignment(wrap_text=True, vertical="center", horizontal="center")
    for i, row in enumerate(data, r0 + 1):
        for j, v in enumerate(row, 1):
            c = ws.cell(i, j, v)
            if isinstance(v, date):
                c.number_format = "DD.MM.YYYY"
            c.alignment = C if j >= center_from and not isinstance(v, str) else W
    if widths:
        for j, w in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(j)].width = w
    ws.freeze_panes = ws.cell(r0 + 1, 1)
    return r0 + len(data) + 2


