# префиксы заказчиков и партнёров перед маркой (МТС, МГТС, РТК, ЭРТХ, ВПК, NKL, ELAN, РИТ, ДКС, IS, БГЭ), ОПЫТ, ГОЗ…, «ОК» — торговая марка
PREFIXES = r"^(?:~\s*|U\s+|ОПЫТ\s+|ОП\s+|МТС\s+|МГТС\s+|РТК\s+|ЭРТХ\s+|ВПК\s+|NKL\s+|ELAN\s+|РИТ\s+|ДКС\s+|IS\s+|БГЭ\s+|ГОЗ[\d.,]*\s*(?:ГП\s+)?|ОК\s+|ГП\s+|микро\s+|W\s+)+"


def brand_of(name: str) -> str | None:
    s = (name or "").strip()
    s = re.sub(PREFIXES, "", s, flags=re.I)
    m = re.match(r"([A-Za-zА-Яа-яЁё]+)", s)
    if not m:
        return None
    tok = m.group(1).upper().replace("Ё", "Е")
    # ТсОС/ТсПО пишутся со строчной «с»; ДПТс, ДОТс, ДОТа, ДПОм, ТПОм, ТПОд — буква после основы
    for b in sorted(BRANDS, key=len, reverse=True):
        if tok.startswith(b):
            return b
    return tok[:6]


def decode(name: str) -> dict:
    b = brand_of(name)
    g, use, arm = BRANDS.get(b, ("не определена", "", ""))
    kn = re.search(r"(\d+(?:[.,]\d+)?)\s*кН", name or "")
    kn = float(kn.group(1).replace(",", ".")) if kn else None
    if b == "ДПТС" and kn is not None and kn <= 2.7:
        g, use = "канализация/трубы", "в кабельную канализацию (ДПТс 2,7 кН)"
    if b == "ТОС" and kn is not None and kn <= 2.7:
        g, use = "канализация/трубы", "в кабельную канализацию (ТОС 2,7 кН)"
    # по ТУ 3587-001-88083123-2010 (позиция брони Д/Д2) и ТУ Окей-Кабеля: броня из стеклопластиковых прутков
    glass_armour = b in ("ДПД", "ТОД", "ОКГД")
    # стеклопластиковые прутки как силовые элементы: дропы «2Д», выносной пруток, райзеры ОБВ/ОМВ
    glass_rod = glass_armour or b in ("ТПОД", "ДПОД", "ОКД", "ОКДК", "ОКДБ", "ОБВ", "ОМВ", "ОВВ")
    return {"brand": b, "group": g, "use": use, "armour": arm, "kn": kn, "glass_armour": glass_armour, "glass_rod": glass_rod,
            "double": bool(re.match(r"^[А-ЯA-Z]+2", re.sub(PREFIXES, "", (name or "").strip(), flags=re.I).upper())),
            "fire": bool(re.search(r"FR|нг|FRHF|LTx", name or "", flags=re.I)), "trial": "ОПЫТ" in (name or "").upper()}
