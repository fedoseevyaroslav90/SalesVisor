def brand_of(name: str | None) -> str | None:
    """Марка — первое слово после префиксов; у партнёрских и служебных приставок без пробела в списке
    («МГФН ДПТ-П…», «ГП БСПз ОКПС…», «КД-ОВК…») — второе или третье слово, если оно известная марка."""
    s = PREFIXES.sub("", (name or "").strip())
    toks = [t.upper().replace("Ё", "Е") for t in re.findall(r"[A-Za-zА-Яа-яЁё0-9]+", s)[:3]]
    if not toks:
        return None
    if toks[0] in OTHER:
        return toks[0]
    for tok in toks:
        for b in _BY_LEN:
            if tok.startswith(b):
                return b
    return re.sub(r"\d+$", "", toks[0])[:8] or None


def decode(name: str | None) -> dict:
    b = brand_of(name)
    group, use, armour = BRANDS.get(b, (OTHER.get(b, "не определена"), "", ""))
    m = re.search(r"(\d+(?:[.,]\d+)?)\s*кН", name or "")
    kn = float(m.group(1).replace(",", ".")) if m else None
    if b in ("ДПТС", "ТОС") and kn is not None and kn <= 2.7:
        group, use = "канализация/трубы", f"в кабельную канализацию ({b} {kn:g} кН)"
    glass_armour = b in ("ДПД", "ТОД", "ОКГД")
    if group == "грунт":
        group = "грунт — стеклопластик" if glass_armour else "грунт — сталь"
    return {"brand": b, "group": group, "use": use, "armour": armour, "kn": kn, "glass_armour": glass_armour,
            "trial": "ОПЫТ" in (name or "").upper()}
